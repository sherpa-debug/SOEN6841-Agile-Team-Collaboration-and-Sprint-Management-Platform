-- PostgreSQL schema for SprintProof's course, team, sprint, task, and evidence data.

BEGIN;

CREATE TABLE IF NOT EXISTS course (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    term TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS team (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES course(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    repo TEXT,
    invite_code TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    github_login TEXT NOT NULL UNIQUE,
    github_id TEXT UNIQUE,
    name TEXT,
    avatar_url TEXT,
    email TEXT,
    role TEXT NOT NULL DEFAULT 'student'
        CHECK (role IN ('student', 'ta', 'instructor'))
);

ALTER TABLE app_user ADD COLUMN IF NOT EXISTS github_id TEXT;
ALTER TABLE app_user ADD COLUMN IF NOT EXISTS avatar_url TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS idx_app_user_github_id ON app_user(github_id) WHERE github_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS team_member (
    team_id BIGINT NOT NULL REFERENCES team(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    PRIMARY KEY (team_id, user_id)
);

CREATE TABLE IF NOT EXISTS team_invite (
    code_hash TEXT PRIMARY KEY,
    team_id BIGINT NOT NULL REFERENCES team(id) ON DELETE CASCADE,
    created_by BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS rubric_criterion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES course(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    UNIQUE (course_id, name)
);

CREATE TABLE IF NOT EXISTS sprint (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT NOT NULL REFERENCES team(id) ON DELETE CASCADE,
    number INTEGER NOT NULL CHECK (number > 0),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    CHECK (end_date >= start_date),
    UNIQUE (team_id, number)
);

CREATE TABLE IF NOT EXISTS task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key TEXT NOT NULL,
    sprint_id BIGINT NOT NULL REFERENCES sprint(id) ON DELETE CASCADE,
    assignee_id BIGINT REFERENCES app_user(id) ON DELETE SET NULL,
    title TEXT NOT NULL,
    type TEXT NOT NULL
        CHECK (type IN ('Requirements', 'Design', 'Implementation', 'Testing', 'Documentation')),
    points INTEGER NOT NULL CHECK (points >= 0),
    status TEXT NOT NULL DEFAULT 'todo'
        CHECK (status IN ('todo', 'in_progress', 'done')),
    UNIQUE (sprint_id, key)
);

CREATE TABLE IF NOT EXISTS task_criterion (
    task_id BIGINT NOT NULL REFERENCES task(id) ON DELETE CASCADE,
    criterion_id BIGINT NOT NULL REFERENCES rubric_criterion(id) ON DELETE CASCADE,
    PRIMARY KEY (task_id, criterion_id)
);

CREATE TABLE IF NOT EXISTS peer_checkin (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sprint_id BIGINT NOT NULL REFERENCES sprint(id) ON DELETE CASCADE,
    rater_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    ratee_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    rating INTEGER CHECK (rating BETWEEN 1 AND 5),
    comment TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'submitted')),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (rater_id <> ratee_id),
    CHECK (status <> 'submitted' OR (rating IS NOT NULL AND length(trim(comment)) > 0)),
    UNIQUE (sprint_id, rater_id, ratee_id)
);

CREATE TABLE IF NOT EXISTS ai_usage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES task(id) ON DELETE CASCADE,
    user_id BIGINT REFERENCES app_user(id) ON DELETE SET NULL,
    tool TEXT NOT NULL,
    purpose TEXT NOT NULL,
    verified BOOLEAN NOT NULL DEFAULT FALSE,
    verification_check TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (NOT verified OR length(trim(verification_check)) > 0)
);

CREATE TABLE IF NOT EXISTS commits (
    sha TEXT PRIMARY KEY,
    team_id BIGINT NOT NULL REFERENCES team(id) ON DELETE CASCADE,
    task_id BIGINT REFERENCES task(id) ON DELETE SET NULL,
    author_id BIGINT REFERENCES app_user(id) ON DELETE SET NULL,
    message TEXT NOT NULL,
    committed_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS pull_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT NOT NULL REFERENCES team(id) ON DELETE CASCADE,
    number INTEGER NOT NULL CHECK (number > 0),
    task_id BIGINT REFERENCES task(id) ON DELETE SET NULL,
    author_id BIGINT REFERENCES app_user(id) ON DELETE SET NULL,
    state TEXT NOT NULL CHECK (state IN ('open', 'closed', 'merged')),
    merged_at TIMESTAMPTZ,
    UNIQUE (team_id, number)
);

CREATE INDEX IF NOT EXISTS idx_team_course_id ON team(course_id);
CREATE INDEX IF NOT EXISTS idx_team_member_user_id ON team_member(user_id);
CREATE INDEX IF NOT EXISTS idx_team_invite_team_expiry ON team_invite(team_id, expires_at);
CREATE INDEX IF NOT EXISTS idx_rubric_criterion_course_id ON rubric_criterion(course_id);
CREATE INDEX IF NOT EXISTS idx_sprint_team_dates ON sprint(team_id, start_date, end_date);
CREATE INDEX IF NOT EXISTS idx_task_assignee_id ON task(assignee_id);
CREATE INDEX IF NOT EXISTS idx_task_criterion_criterion_id ON task_criterion(criterion_id);
CREATE INDEX IF NOT EXISTS idx_peer_checkin_ratee ON peer_checkin(sprint_id, ratee_id);
CREATE INDEX IF NOT EXISTS idx_ai_usage_task_id ON ai_usage(task_id);
CREATE INDEX IF NOT EXISTS idx_commits_team_committed_at ON commits(team_id, committed_at);
CREATE INDEX IF NOT EXISTS idx_commits_task_id ON commits(task_id);
CREATE INDEX IF NOT EXISTS idx_pull_request_task_id ON pull_request(task_id);

COMMIT;
